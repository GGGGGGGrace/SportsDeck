"use client";

import { useEffect, useState } from "react";
import { apiFetch } from "@/lib/api";

export default function DigestPage() {
  const [content, setContent] = useState<string | null>(null);
  const [cached, setCached] = useState(false);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [generatedAt] = useState(() => new Date());

  useEffect(() => {
    async function fetchDigest() {
      try {
        const data = await apiFetch("/api/digest");
        setContent(data.content);
        setCached(data.cached);
      } catch (err: any) {
        setError(err.message || "Failed to load digest.");
      } finally {
        setLoading(false);
      }
    }
    fetchDigest();
  }, []);

  return (
    <div className="mx-auto max-w-2xl space-y-6">
      {/* Header */}
      <div className="rounded-3xl border border-zinc-200 bg-gradient-to-br from-zinc-100 via-white to-zinc-200 p-8 dark:border-zinc-800 dark:from-zinc-900 dark:via-zinc-950 dark:to-zinc-900">
        <p className="text-sm font-semibold uppercase tracking-widest text-zinc-400">
          AI-Powered
        </p>
        <h1 className="mt-1 text-3xl font-black tracking-tight">
          Daily Digest
        </h1>
        <p className="mt-2 text-sm text-zinc-500 dark:text-zinc-400">
          A summary of today's top discussions, recent match results, and league
          standings — generated by AI.
        </p>
        <p className="mt-1 text-xs text-zinc-400">
          {generatedAt.toLocaleDateString("en-GB", {
            weekday: "long",
            day: "numeric",
            month: "long",
            year: "numeric",
          })}
        </p>
      </div>

      {/* Content */}
      <div className="rounded-2xl border border-zinc-200 bg-white/60 p-6 dark:border-zinc-800 dark:bg-zinc-900/60">
        {loading && (
          <div className="space-y-3">
            <p className="text-sm text-zinc-500">
              ⚙️ Generating your digest — this may take a moment…
            </p>
            {[...Array(4)].map((_, i) => (
              <div
                key={i}
                className={`h-4 animate-pulse rounded-full bg-zinc-100 dark:bg-zinc-800 ${
                  i === 3 ? "w-2/3" : "w-full"
                }`}
              />
            ))}
          </div>
        )}

        {error && !loading && (
          <p className="text-sm text-red-500">⚠️ {error}</p>
        )}

        {content && !loading && (
          <>
            <div className="prose prose-zinc max-w-none dark:prose-invert">
              <p className="whitespace-pre-wrap leading-relaxed text-zinc-700 dark:text-zinc-300">
                {content}
              </p>
            </div>
            <div className="mt-6 flex items-center justify-between border-t border-zinc-100 pt-4 dark:border-zinc-800">
              <p className="text-xs text-zinc-400">
                🤖 Generated by{" "}
                <span className="font-medium">facebook/bart-large-cnn</span>{" "}
                via HuggingFace
              </p>
              {cached && (
                <span className="rounded-full bg-zinc-100 px-2 py-0.5 text-xs text-zinc-500 dark:bg-zinc-800 dark:text-zinc-400">
                  ✓ Cached today
                </span>
              )}
            </div>
          </>
        )}
      </div>

      {/* Info card */}
      <div className="grid grid-cols-3 gap-3">
        <div className="rounded-2xl border border-zinc-200 p-4 text-center dark:border-zinc-800">
          <p className="text-2xl">💬</p>
          <p className="mt-1 text-xs font-semibold text-zinc-500">
            Top Threads
          </p>
        </div>
        <div className="rounded-2xl border border-zinc-200 p-4 text-center dark:border-zinc-800">
          <p className="text-2xl">⚽</p>
          <p className="mt-1 text-xs font-semibold text-zinc-500">
            Recent Results
          </p>
        </div>
        <div className="rounded-2xl border border-zinc-200 p-4 text-center dark:border-zinc-800">
          <p className="text-2xl">🏆</p>
          <p className="mt-1 text-xs font-semibold text-zinc-500">
            Standings
          </p>
        </div>
      </div>
    </div>
  );
}
